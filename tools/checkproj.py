#!/usr/bin/env python3
"""Structural sanity check for the generated project.pbxproj.

Not a substitute for Xcode, but it catches the mistakes that matter when a
project file is generated by hand: dangling object references, duplicate
identifiers and unbalanced braces.

    python3 tools/checkproj.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PBXPROJ = ROOT / "Inkwell.xcodeproj" / "project.pbxproj"
SCHEME = ROOT / "Inkwell.xcodeproj" / "xcshareddata" / "xcschemes" / "Inkwell.xcscheme"

OBJECT_RE = re.compile(r"^\t\t([0-9A-F]{24})\s*(?:/\*.*?\*/)?\s*=\s*\{", re.MULTILINE)
UUID_RE = re.compile(r"\b([0-9A-F]{24})\b")


def main() -> int:
    problems: list[str] = []

    if not PBXPROJ.exists():
        print(f"missing {PBXPROJ} — run tools/genproj.py first")
        return 1

    text = PBXPROJ.read_text(encoding="utf-8")

    # 1. Brace balance.
    depth = 0
    for index, character in enumerate(text):
        if character == "{":
            depth += 1
        elif character == "}":
            depth -= 1
            if depth < 0:
                problems.append(f"unbalanced closing brace at offset {index}")
                break
    if depth != 0:
        problems.append(f"unbalanced braces (final depth {depth})")

    # 2. Parenthesis balance.
    if text.count("(") != text.count(")"):
        problems.append("unbalanced parentheses")

    # 3. Every object has an isa and a unique id.
    definitions: dict[str, str] = {}
    for match in OBJECT_RE.finditer(text):
        uuid = match.group(1)
        if uuid in definitions:
            problems.append(f"duplicate object id {uuid}")
        block = text[match.end(): match.end() + 400]
        isa = re.search(r"isa\s*=\s*([A-Za-z]+)", block)
        if not isa:
            problems.append(f"object {uuid} has no isa")
            definitions[uuid] = "unknown"
        else:
            definitions[uuid] = isa.group(1)

    if not definitions:
        problems.append("no objects found — the file is probably malformed")

    # 4. Every referenced id is defined.
    referenced = set(UUID_RE.findall(text))
    dangling = sorted(referenced - set(definitions))
    for uuid in dangling:
        problems.append(f"dangling reference to {uuid}")

    # 5. The objects the build absolutely needs.
    required = {
        "PBXProject": 1,
        "PBXNativeTarget": 2,
        "PBXSourcesBuildPhase": 2,
        "PBXResourcesBuildPhase": 2,
        "PBXFrameworksBuildPhase": 2,
        "XCBuildConfiguration": 6,
        "XCConfigurationList": 3,
        "PBXGroup": 1,
    }
    counts: dict[str, int] = {}
    for isa in definitions.values():
        counts[isa] = counts.get(isa, 0) + 1
    for isa, minimum in required.items():
        if counts.get(isa, 0) < minimum:
            problems.append(f"expected at least {minimum} {isa}, found {counts.get(isa, 0)}")

    # 6. rootObject exists.
    root = re.search(r"rootObject\s*=\s*([0-9A-F]{24})", text)
    if not root:
        problems.append("no rootObject")
    elif root.group(1) not in definitions:
        problems.append("rootObject points at a missing object")

    # 7. The scheme references real target ids.
    if not SCHEME.exists():
        problems.append("shared scheme is missing")
    else:
        scheme = SCHEME.read_text(encoding="utf-8")
        for uuid in set(UUID_RE.findall(scheme)):
            if uuid not in definitions:
                problems.append(f"scheme references unknown target {uuid}")
        if scheme.count("<BuildableReference") < 4:
            problems.append("scheme looks incomplete")

    if problems:
        print("FAIL")
        for problem in problems:
            print(f"  - {problem}")
        return 1

    print(f"OK  {len(definitions)} objects, {len(referenced)} references resolved")
    for isa in sorted(counts):
        print(f"    {isa}: {counts[isa]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())